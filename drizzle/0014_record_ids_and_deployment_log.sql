-- Lead ID, Deal ID, Deployment ID, and dropped vehicles (Vivek, 3 Nov).
--
-- 1. leads.ref and opportunities.ref: a short running number, shown as
--    L-0001 / D-0001. Existing rows are numbered in the order they were
--    created (leads by enquiry date, then creation), new rows by the database.
-- 2. opportunities.vehicles_dropped: sold vehicles that will never go out.
--    deployed + dropped <= fleet_size replaces the old deployed <= fleet_size.
-- 3. deployment_events: the deployment log, one row per change, each with a
--    Deployment ID (DP-0001). Every deal that already has vehicles out gets
--    one carried-over row so the log adds up to the totals; its day is
--    unknown, so happened_on is left null.
--
-- Additive: nothing existing is renamed or dropped, and the replaced check
-- only widens what it measures. Apply it BEFORE the code that reads it
-- deploys — the Deployments screen and the exports select these columns.
-- Plain statements, no DO blocks, so the Neon connector can run it as is.

CREATE TYPE "public"."deployment_event_kind" AS ENUM('deployed', 'dropped');--> statement-breakpoint
CREATE TYPE "public"."drop_reason" AS ENUM('vehicle_unavailable', 'driver_unavailable', 'charging_constraint', 'demand_lost', 'other');--> statement-breakpoint

-- Lead ID
ALTER TABLE "leads" ADD COLUMN "ref" integer;--> statement-breakpoint
UPDATE "leads" SET "ref" = n.rn
  FROM (SELECT "id", row_number() OVER (ORDER BY "enquiry_date", "created_at", "id") AS rn FROM "leads") n
  WHERE "leads"."id" = n."id";--> statement-breakpoint
ALTER TABLE "leads" ALTER COLUMN "ref" SET NOT NULL;--> statement-breakpoint
ALTER TABLE "leads" ALTER COLUMN "ref" ADD GENERATED BY DEFAULT AS IDENTITY (sequence name "leads_ref_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1);--> statement-breakpoint
SELECT setval('leads_ref_seq', coalesce((SELECT max("ref") FROM "leads"), 0) + 1, false);--> statement-breakpoint
CREATE UNIQUE INDEX "leads_ref_idx" ON "leads" USING btree ("ref");--> statement-breakpoint

-- Deal ID
ALTER TABLE "opportunities" ADD COLUMN "ref" integer;--> statement-breakpoint
UPDATE "opportunities" SET "ref" = n.rn
  FROM (SELECT "id", row_number() OVER (ORDER BY "created_at", "id") AS rn FROM "opportunities") n
  WHERE "opportunities"."id" = n."id";--> statement-breakpoint
ALTER TABLE "opportunities" ALTER COLUMN "ref" SET NOT NULL;--> statement-breakpoint
ALTER TABLE "opportunities" ALTER COLUMN "ref" ADD GENERATED BY DEFAULT AS IDENTITY (sequence name "opportunities_ref_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1);--> statement-breakpoint
SELECT setval('opportunities_ref_seq', coalesce((SELECT max("ref") FROM "opportunities"), 0) + 1, false);--> statement-breakpoint
CREATE UNIQUE INDEX "opps_ref_idx" ON "opportunities" USING btree ("ref");--> statement-breakpoint

-- Dropped vehicles
ALTER TABLE "opportunities" ADD COLUMN "vehicles_dropped" integer DEFAULT 0 NOT NULL;--> statement-breakpoint
ALTER TABLE "opportunities" DROP CONSTRAINT "opps_deployed_within_fleet";--> statement-breakpoint
ALTER TABLE "opportunities" ADD CONSTRAINT "opps_deployed_within_fleet" CHECK ("opportunities"."vehicles_deployed" >= 0 and "opportunities"."vehicles_dropped" >= 0 and "opportunities"."vehicles_deployed" + "opportunities"."vehicles_dropped" <= "opportunities"."fleet_size");--> statement-breakpoint

-- The deployment log
CREATE TABLE "deployment_events" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"ref" integer GENERATED BY DEFAULT AS IDENTITY (sequence name "deployment_events_ref_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"organization_id" uuid NOT NULL,
	"opportunity_id" uuid NOT NULL,
	"kind" "deployment_event_kind" NOT NULL,
	"vehicles" integer NOT NULL,
	"happened_on" date,
	"reason" "drop_reason",
	"note" text,
	"user_id" uuid,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "deployment_events_nonzero" CHECK ("deployment_events"."vehicles" <> 0),
	CONSTRAINT "deployment_events_drop_requires_reason" CHECK ("deployment_events"."kind" <> 'dropped' or "deployment_events"."vehicles" < 0 or "deployment_events"."reason" is not null),
	CONSTRAINT "deployment_events_other_requires_note" CHECK ("deployment_events"."reason" is distinct from 'other' or "deployment_events"."note" is not null)
);
