-- Strategic customer meetings.
--
-- Five new tables and one new column, nothing existing is touched, so it is
-- safe to apply before the code that reads it deploys. Apply it BEFORE that
-- code: the Customers page selects `accounts.is_strategic` on every load, and
-- the Meetings screens select all of these.
--
-- What it adds:
--   contacts             people at the customer's end, reusable across meetings
--   meetings             one meeting (M-0001), optionally a follow-up to another
--   meeting_attendees    who was in the room — our user, or their contact
--   meeting_follow_ups   what was committed to, with an owner and a date
--   meeting_topics       admin-managed list of what customers keep raising
--   meeting_topic_links  which topics a meeting touched
--   accounts.is_strategic  the watchlist flag an admin sets
--
-- The last statement seeds the topic list for every organization that already
-- exists. It is an INSERT ... SELECT with ON CONFLICT DO NOTHING, so that one
-- statement can be re-run on its own and adds nothing the second time. The
-- file as a whole is not re-runnable — CREATE TYPE is not guarded, the same as
-- every migration before it.
--
-- Verified on a local Postgres 16 built from 0000-0015: every check constraint
-- refuses what it should (a held meeting with no notes, an attendee who is
-- both ours and theirs, a follow-up with no owner or two, a dropped one with
-- no reason), two customer attendees on one meeting are allowed where the same
-- one twice is not, deleting a customer that has meetings is refused, and the
-- topic seed is idempotent.

