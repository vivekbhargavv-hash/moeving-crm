-- Carry today's counts into the log, oldest deal first.
INSERT INTO "deployment_events" ("organization_id", "opportunity_id", "kind", "vehicles", "happened_on", "note")
  SELECT "organization_id", "id", 'deployed', "vehicles_deployed", NULL,
         'Recorded before the deployment log existed; the day was not captured.'
  FROM "opportunities"
  WHERE "vehicles_deployed" > 0
  ORDER BY "ref";
